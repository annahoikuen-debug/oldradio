import re

# プロンプトの「見出し語」だけを落とすためのパターン。
# 意味語（"ヒット曲" など）で判定すると原稿本文まで消えるため、
# 見出し語・コロン付きラベル・プロンプト指示文で判定する。
_LABEL_ONLY_PATTERNS = [
    r"^\s*オープニング挨拶.*$",
    r"^\s*その日の主要.*$",
    r"^\s*主要ニュース.*$",
    r"^\s*主要な出来事.*$",
    r"^\s*くらしの風景.*$",
    r"^\s*暮らし.*流行.*$",
    r"^\s*リスナーへの語りかけ.*$",
    r"^\s*共感メッセージ.*$",
    r"^\s*曲振り.*$",
    r"^\s*エンディング挨拶.*$",
    r"^\s*ニュースバリエーション.*$",
    r"^\s*選択したニュース.*$",
    r"^\s*自然なつなぎ.*$",
    # 「条件:」「口調:」など、単独行またはコロン付きのラベル行
    r"^\s*(?:条件|口調|構成|対象年|日付|重要度|お祝い対象者)\s*[:：].*$",
    r"^\s*(?:条件|口調|構成)\s*$",
    # プロンプトの指示文（原稿をそのまま読み上げると説明書のようになる）
    r"^\s*あなたは.*ラジオパーソナリティです。.*$",
    r"^\s*リスナーの記念日.*$",
    r"^\s*以上のセグメント構成で原稿を書いてください.*$",
    r"^\s*以下のセグメント構成で原稿を書いてください.*$",
    r"^\s*各セクションは「###.*$",
    r"^\s*曲とトークを交互に配置するラジオ番組です\s*[:：]?\s*$",
    r"^\s*オープニング曲\s*→.*$",
    r"^\s*最後は「.*」で締めくくる.*$",
    r"^\s*[-*・]\s*口調\s*[:：].*$",
    r"^\s*[-*・]\s*日本国内の出来事に限定.*$",
    r"^\s*[-*・]\s*各セクション間に自然なつなぎ.*$",
    r"^\s*[-*・]\s*自然なつなぎ.*$",
    r"^\s*[-*・]\s*曲振り.*$",
    r"^\s*[-*・]\s*日本国内.*$",
]

# 指し対象のない「純粋なラベル行」（"それでは、ヒット曲をお届けします" など）。
# "この年のヒット曲" や "懐かしい名曲「X」（Y）" のように具体的な言及がある行は
# 原稿の一部なので残す。
_GENERIC_SONG_CUE = re.compile(
    r"^[ \t]*(?:(?:それでは|続いて|では|さて)[ \t]*[、,][ \t]*)?"
    r"(?:ヒット曲|名曲|曲)[ \t]*を?[ \t]*"
    r"(?:お届け|お渡し)(?:します|いたします)(?:た|い)?[ \t]*[。．]?[ \t]*$",
    re.MULTILINE,
)


# 演出指示（ステージディレクション）。
# LLM は原稿の中に「（※音楽が流れる）」のような演出的注記を挿入してくることがある。
# これをそのまま TTS へ渡すと「※音楽が流れる」と声で読んでしまい、
# しかも `### 曲1` 見出しと組{${0}接触到 1 つの幻のトーク，造成不应该读出来的词。
# 行全体が括弧／※ で包まれているものだけを消す（本文中の括弧は残す）。
_STAGE_DIRECTION_LINE = re.compile(
    r"^[ \t]*(?:[（(【\[][ \t]*)?[※*]+[ \t]*[^）)】\]※*\n]{0,60}[）)】\]]?[ \t]*$",
    re.MULTILINE,
)
_STAGE_DIRECTION_PAREN = re.compile(r"[（(【\[][ \t]*※[^）)】\]]{0,60}[）)】\]]")
# 段落全体が括弧で包まれただけの行（"（番組テーマ曲のイントロがフェードアウト）"）。
# 地の文が丸括弧だけで構成されることはないため、これはいずれ演出指示。
_PAREN_ONLY_LINE = re.compile(r"^[ \t]*[（(【\[][^\n）)】\]]{1,80}[）)】\]][ \t]*$", re.MULTILINE)
# Markdown の水平線（原稿の区切りに使われるだけなので読み上げ不要）
_HRULE = re.compile(r"^[ \t]*-{3,}[ \t]*$", re.MULTILINE)


def clean_script_for_tts(text: str) -> str:
    """TTS読み上げ用に原稿から構造的・メタ的要素を除去

    曲振り台詞（"それでは、この年のヒット曲をお届けします"）は原稿の一部なので
    消さない。落とすのはプロンプトの指示語と見出し行だけ。
    """
    if not text:
        return ""

    cleaned = text

    # 0. 演出指示（"（※音楽が流れる）" など）と水平線を除去
    #    これを残すと司会が「※音楽が流れる」と読み上げてしまう。
    cleaned = _STAGE_DIRECTION_LINE.sub("", cleaned)
    cleaned = _PAREN_ONLY_LINE.sub("", cleaned)
    cleaned = _STAGE_DIRECTION_PAREN.sub("", cleaned)
    cleaned = _HRULE.sub("", cleaned)

    # 1. アスタリスク除去（マークダウン記法）
    cleaned = re.sub(r"\*{1,3}", "", cleaned)

    # 2. Markdown見出し行を除去（### オープニング 等）
    cleaned = re.sub(r"^\s*#{1,6}\s+.*$", "", cleaned, flags=re.MULTILINE)

    # 3. 番号付きセクションヘッダー除去（1. 2. 3. など）
    cleaned = re.sub(r"^\s*\d+[\.、]\s*.+$", "", cleaned, flags=re.MULTILINE)

    # 4. 見出し・ラベル行のみ除去
    for pattern in _LABEL_ONLY_PATTERNS:
        cleaned = re.sub(pattern, "", cleaned, flags=re.MULTILINE)

    # 5. 指し対象のない曲振りラベル行のみ除去
    cleaned = _GENERIC_SONG_CUE.sub("", cleaned)

    # 6. 空行の連続を1つにまとめる
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)

    # 7. 行頭・行末の空白除去
    cleaned = "\n".join(line.strip() for line in cleaned.split("\n"))

    # 8. 先頭・末尾の空白除去
    cleaned = cleaned.strip()

    return cleaned
